CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255),
    description VARCHAR(2000),
    status VARCHAR(50),
    start_time TIMESTAMP,
    duration BIGINT
);

CREATE TABLE IF NOT EXISTS epics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255),
    description VARCHAR(2000),
    status VARCHAR(50),
    start_time TIMESTAMP,
    duration BIGINT,
    end_time TIMESTAMP
);

CREATE TABLE IF NOT EXISTS subtasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255),
    description VARCHAR(2000),
    status VARCHAR(50),
    start_time TIMESTAMP,
    duration BIGINT,
    epic_id INTEGER NOT NULL,

    CONSTRAINT fk_epic
        FOREIGN KEY (epic_id)
        REFERENCES epics(id)
        ON DELETE CASCADE
);
